#!/usr/bin/env python3
# Bundles the built Leaflet Link (link/LeafletLink.3dsx) into js/linkapp.js, so Cartridge Sync can install or update
# it on a 3DS over Wi-Fi, even when Leaflet runs from file:// where pages can't read other local files.
# Run after `make -C link` (the Makefile does it for you).
import base64, os, re, sys, zlib
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
app = open(os.path.join(root, 'link', 'LeafletLink.3dsx'), 'rb').read()
version = re.search(r'#define LL_VERSION "([^"]+)"', open(os.path.join(root, 'link', 'source', 'version.h')).read()).group(1)
out = os.path.join(root, 'js', 'linkapp.js')
b64 = base64.b64encode(app).decode()
with open(out, 'w') as f:
    f.write('// Generated by tools/build_link_js.py from link/LeafletLink.3dsx. Don\'t edit.\n')
    f.write(f"window.LEAFLET_LINK_APP = {{ version: '{version}', size: {len(app)}, crc: '{zlib.crc32(app):08x}', data:\n")
    f.write(''.join(f"  '{b64[i:i + 160]}' +\n" for i in range(0, len(b64), 160)) + "  '' };\n")
print(f'js/linkapp.js: Leaflet Link {version}, {len(app):,} bytes')
